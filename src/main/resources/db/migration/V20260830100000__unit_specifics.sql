-- ── what each unit, or each typology, actually has ───────────────────────────────────────────────

/*
 * One table for both, because the inheritance rule needs them comparable.
 *
 * A row belongs to a unit or to a typology, never both. A unit with any rows of its own has exactly those; a
 * unit with none inherits its typology's. Two tables would have made that rule a join across two shapes and
 * the "override with fewer features" case awkward to express.
 */
CREATE TABLE unit_features (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    unit_id         BIGINT REFERENCES development_units (id),
    unit_type_id    BIGINT REFERENCES development_unit_types (id),
    feature_code    VARCHAR(48) NOT NULL REFERENCES unit_feature_configs (code),

    status          INTEGER      NOT NULL DEFAULT 1,
    status_flag     VARCHAR(32)  NOT NULL DEFAULT 'Active',
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by      VARCHAR(64),

    CONSTRAINT ck_unit_feature_owner CHECK (
        (unit_id IS NOT NULL)::int + (unit_type_id IS NOT NULL)::int = 1)
);

-- One row per feature per owner: saying a flat has a pantry twice is not saying it twice as much.
CREATE UNIQUE INDEX uk_unit_feature_unit ON unit_features (unit_id, feature_code)
    WHERE unit_id IS NOT NULL AND status <> 5;
CREATE UNIQUE INDEX uk_unit_feature_type ON unit_features (unit_type_id, feature_code)
    WHERE unit_type_id IS NOT NULL AND status <> 5;

CREATE INDEX idx_unit_feature_lookup ON unit_features (unit_id) WHERE unit_id IS NOT NULL AND status <> 5;
CREATE INDEX idx_unit_feature_type_lookup ON unit_features (unit_type_id)
    WHERE unit_type_id IS NOT NULL AND status <> 5;
