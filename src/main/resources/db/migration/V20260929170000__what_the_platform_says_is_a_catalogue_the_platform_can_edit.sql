-- What the platform says is a catalogue the platform can edit.
--
-- Every event that tells somebody something is a row: who it is for, under which consent, whether it is
-- on, on which channels by default, and the words — a subject and a line with placeholders the module
-- fills. An organisation may switch an event off or choose channels for its own people, and reword it
-- when the platform's setting allows. The wording moves out of Java; nothing that is said changes today.

CREATE TABLE notification_events (
    code          VARCHAR(40)  PRIMARY KEY,
    -- BUYER | SELLER_STAFF | PLATFORM_STAFF | VALUER | REQUESTER (the seller or the bank that commissioned it)
    audience      VARCHAR(16)  NOT NULL,
    purpose       VARCHAR(32)  NOT NULL,
    enabled       BOOLEAN      NOT NULL DEFAULT true,
    -- CSV of EMAIL, SMS, IN_APP: the platform's default; consent still decides per person.
    channels      VARCHAR(32)  NOT NULL DEFAULT 'EMAIL,SMS,IN_APP',
    subject       VARCHAR(255) NOT NULL,
    line          TEXT         NOT NULL,
    description   VARCHAR(255) NOT NULL,
    placeholders  VARCHAR(255) NOT NULL DEFAULT '',
    -- The module composes this one itself (a digest with cards); the catalogue decides only on/off and channels.
    composed      BOOLEAN      NOT NULL DEFAULT false,
    sort_order    INTEGER      NOT NULL DEFAULT 0,
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by    VARCHAR(64),
    CONSTRAINT ck_notification_event_audience CHECK (audience IN ('BUYER', 'SELLER_STAFF', 'PLATFORM_STAFF', 'VALUER', 'REQUESTER')),
    CONSTRAINT ck_notification_event_purpose CHECK (purpose IN ('TRANSACTIONAL', 'PROPERTY_ALERTS', 'PROMOTIONAL'))
);

CREATE TABLE notification_event_overrides (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_code      VARCHAR(40) NOT NULL REFERENCES notification_events (code),
    tenant_id       BIGINT,
    institution_id  BIGINT,
    -- Null means "as the platform says".
    enabled         BOOLEAN,
    channels        VARCHAR(32),
    subject         VARCHAR(255),
    line            TEXT,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by      VARCHAR(64),
    CONSTRAINT ck_notification_override_owner CHECK ((tenant_id IS NULL) <> (institution_id IS NULL))
);
CREATE UNIQUE INDEX uk_notification_override ON notification_event_overrides (event_code, coalesce(tenant_id, 0), coalesce(institution_id, 0));

