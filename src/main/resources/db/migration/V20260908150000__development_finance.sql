-- Development finance: where the money went, and when it will be finished
--
-- See claudedocs/DEVELOPMENT_FINANCE_AND_PROGRAMME_PLAN.md. The phase table already carried a budget, a
-- planned spend, a committed and a spent figure — typed into an editor and overwritten in place. That is a
-- snapshot, and "how has this project been consuming funds" is a question about time. This migration gives
-- the money a history.
--
-- <h2>A ledger, and the phase figures derived from it</h2>
--
-- `development_expenditures` is one row per cost event, dated, categorised and attributable. The phase's
-- `committed_amount` and `spent_amount` stop being typed: DevelopmentInventoryService recounts them from the
-- ledger, the way it already recounts every unit tally, so there is one writer. What was typed before today
-- becomes an opening line per phase — dated at the phase's start, referenced OPENING — so the ledger's total
-- equals the old column on day one and nothing anybody entered is lost.
--
-- <h2>Never edited, only voided</h2>
--
-- A cost report a lender has read must not quietly change. A wrong line is voided with a reason and stays,
-- exactly as a payment is. The views sum received lines only.
--
-- <h2>The facility, drawn</h2>
--
-- `facility_drawdowns` is the other half of "funds consumed": what the lender disbursed, dated. Drawn and
-- undrawn are then sums rather than guesses.
--
-- <h2>Categories are configuration</h2>
--
-- Eight are seeded; the platform adds, renames and suspends them the way progress milestones and property
-- types are maintained. A developer's own vocabulary is not refused.
-- ═════════════════════════════════════════════════════════════════════════════════════════════════

