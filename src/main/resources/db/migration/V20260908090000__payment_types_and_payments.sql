    ADD CONSTRAINT ck_payment_amount CHECK (status = 5 OR amount > 0),
    ADD CONSTRAINT ck_payment_void CHECK (
        status <> 4 OR (voided_at IS NOT NULL AND void_reason IS NOT NULL));

