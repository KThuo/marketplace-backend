-- ── 3. Payments ──────────────────────────────────────────────────────────────────────────────────

ALTER TABLE booking_payments RENAME TO payments;

ALTER TABLE payments
    -- Cached from the booking, so the list and the receipt read one table. A receipt printed today must
    -- still read the same after a unit is relabelled or a buyer's name is corrected.
    ADD COLUMN development_id    BIGINT REFERENCES developments (id),
    ADD COLUMN unit_id           BIGINT REFERENCES development_units (id),
    ADD COLUMN development_name  VARCHAR(255),
    ADD COLUMN unit_label        VARCHAR(32),
    ADD COLUMN buyer_name        VARCHAR(160),
    ADD COLUMN buyer_phone       VARCHAR(32),
    /*
     * The configured account this came through, where it came through one — beside `method`, not
     * instead of it. The method is what the system did with the money; this is what a person calls it.
     * The name is copied so a receipt still reads the same after the catalogue row is renamed.
     */
    ADD COLUMN payment_type_id   BIGINT REFERENCES payment_types (id),
    ADD COLUMN payment_type_name VARCHAR(120),
    /*
     * What the booking owed immediately before and after. Both stored, neither derived: `after + amount`
     * is wrong the moment the payment is voided and the balance recomputed, and a receipt states what was
     * true when it was issued.
     */
    ADD COLUMN balance_before    NUMERIC(15, 2),
    ADD COLUMN balance_after     NUMERIC(15, 2),
    ADD COLUMN voided_at         TIMESTAMPTZ,
    ADD COLUMN voided_by         VARCHAR(64),
    ADD COLUMN void_reason       TEXT,
    -- The bank credit behind it, where there was one. Null for anything keyed in by hand.
    ADD COLUMN statement_id      BIGINT REFERENCES pesi_statements (id);

UPDATE payments p
   SET development_id = b.development_id,
       unit_id        = b.unit_id,
       buyer_name     = b.buyer_name,
       buyer_phone    = b.buyer_phone
  FROM unit_bookings b
 WHERE b.id = p.booking_id;

UPDATE payments p SET development_name = d.name FROM developments d WHERE d.id = p.development_id;
UPDATE payments p SET unit_label = u.unit_label FROM development_units u WHERE u.id = p.unit_id;

UPDATE payments p SET statement_id = s.id FROM pesi_statements s WHERE s.mapped_payment_id = p.id;

UPDATE payments p
   SET payment_type_id   = a.payment_type_id,
       payment_type_name = t.name
  FROM pesi_statements s
  JOIN payment_accounts a ON a.id = s.payment_account_id
  JOIN payment_types t ON t.id = a.payment_type_id
 WHERE s.id = p.statement_id;

/*
 * Reversals become voids. The original carries what the reversal said — why, who and when — and the
 * reversal row is archived rather than deleted: this schema keeps every row, and everything the reversal
 * knew now sits on the payment it corrected.
 */
UPDATE payments o
   SET status      = 4,
       status_flag = 'Inactive',
       voided_at   = r.created_at,
       voided_by   = r.created_by,
       void_reason = r.reversal_reason,
       updated_at  = now(),
       updated_by  = 'migration'
  FROM payments r
 WHERE r.reversal_of_id = o.id
   AND r.status <> 5;

UPDATE payments
   SET status = 5, status_flag = 'Deleted', updated_at = now(), updated_by = 'migration'
 WHERE reversal_of_id IS NOT NULL;

