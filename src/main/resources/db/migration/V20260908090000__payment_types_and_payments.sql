-- ── 2. The accounts ──────────────────────────────────────────────────────────────────────────────

CREATE TABLE payment_accounts (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_type_id     BIGINT       NOT NULL REFERENCES payment_types (id),

    /*
     * Whose money lands here. Exactly one, or neither for the platform's own account — the same shape as
     * every other owner pair in this schema, and the reason a lending institution can collect on a
     * development it financed without being a tenant.
     */
    tenant_id           BIGINT       REFERENCES tenants (id),
    institution_id      BIGINT       REFERENCES lending_institutions (id),

    -- One development, or null for every development the owner has.
    development_id      BIGINT       REFERENCES developments (id),

    pay_bill_no         VARCHAR(32),
    /*
     * Null only for cash and cheque, and the CHECK below says so. A mandatory column here is how a live
     * system ends up with the literal string "HODI" in every STK row — typed to get past a field that
     * channel has no use for.
     */
    account_no          VARCHAR(64),
    account_name        VARCHAR(160),
    /*
     * A secondary reference the bank may quote on its notifications. Optional here: the Pesi contract this
     * platform speaks names the account itself, and that is the key. Unique when present so a fallback
     * match can never land on two accounts.
     */
    short_code          VARCHAR(64),

    -- Copied from the catalogue row so an inbound match is one table and one index.
    pesi_type           VARCHAR(50),
    category            VARCHAR(16)  NOT NULL,

    status              INTEGER      NOT NULL DEFAULT 1,
    status_flag         VARCHAR(32)  NOT NULL DEFAULT 'Active',
    search_text         TEXT GENERATED ALWAYS AS (
        lower(coalesce(account_no, '') || ' ' || coalesce(account_name, '') || ' '
              || coalesce(short_code, '') || ' ' || coalesce(pay_bill_no, ''))
    ) STORED,

    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by          VARCHAR(64),
    updated_by          VARCHAR(64),

    CONSTRAINT ck_payment_account_owner CHECK ((tenant_id IS NULL) OR (institution_id IS NULL)),
    CONSTRAINT ck_payment_account_category CHECK (category IN
        ('CASH', 'CHEQUE', 'STK_PUSH', 'TRANSFER', 'VALIDATE')),
    -- An account-based channel carries both halves of the account; a manual one carries neither.
    CONSTRAINT ck_payment_account_fields CHECK (
        (category IN ('CASH', 'CHEQUE') AND account_no IS NULL AND account_name IS NULL)
        OR (category NOT IN ('CASH', 'CHEQUE')
            AND account_no IS NOT NULL AND length(btrim(account_no)) > 0
            AND account_name IS NOT NULL AND length(btrim(account_name)) > 0))
);

-- The inbound match key. Two live rows claiming one till would make whose money it is depend on row order.
CREATE UNIQUE INDEX uk_payment_account_no ON payment_accounts (account_no)
    WHERE account_no IS NOT NULL AND status <> 5;
CREATE UNIQUE INDEX uk_payment_account_short_code ON payment_accounts (short_code)
    WHERE short_code IS NOT NULL AND status <> 5;
-- Cash and cheque once per owner and development. A gateway channel may be configured repeatedly — an
-- organisation really does hold several accounts on one bank — and the index above keeps those apart.
CREATE UNIQUE INDEX uk_payment_account_manual
    ON payment_accounts (coalesce(tenant_id, 0), coalesce(institution_id, 0), payment_type_id,
                         coalesce(development_id, 0))
    WHERE category IN ('CASH', 'CHEQUE') AND status <> 5;

CREATE INDEX idx_payment_account_tenant ON payment_accounts (tenant_id) WHERE tenant_id IS NOT NULL;
CREATE INDEX idx_payment_account_institution ON payment_accounts (institution_id)
    WHERE institution_id IS NOT NULL;
CREATE INDEX idx_payment_account_type ON payment_accounts (payment_type_id, status);
CREATE INDEX idx_payment_account_search ON payment_accounts USING gin (search_text public.gin_trgm_ops);

/*
 * The tills already registered move across with their ids, so the statements that point at them keep
 * pointing at the right row. Every Pesi code the old catalogue held is seeded above, so nothing is lost
 * in the join.
 */
INSERT INTO payment_accounts (id, payment_type_id, tenant_id, institution_id, development_id,
                              account_no, account_name, pesi_type, category,
                              status, status_flag, created_at, updated_at, created_by, updated_by)
SELECT m.id, t.id, m.tenant_id, m.institution_id, NULL,
       m.account_number, m.account_name, t.pesi_provider_type, t.category,
       m.status, m.status_flag, m.created_at, m.updated_at, m.created_by, m.updated_by
  FROM pesi_payment_methods m
  JOIN pesi_super_types s ON s.id = m.super_type_id
  JOIN payment_types t ON t.pesi_provider_type = s.code;

SELECT setval(pg_get_serial_sequence('payment_accounts', 'id'),
              COALESCE((SELECT max(id) FROM payment_accounts), 0) + 1, false);

