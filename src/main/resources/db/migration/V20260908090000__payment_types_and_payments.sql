-- ═════════════════════════════════════════════════════════════════════════════════════════════════
-- Payment types, payment accounts, and payments
--
-- See claudedocs/PAYMENTS_AND_PAYMENT_TYPES_PLAN.md. The short version: this platform already had the
-- first half of this feature under other names — `pesi_super_types` was a catalogue of channels with no
-- cash, no cheque and no flags; `pesi_payment_methods` was an account with an owner and nothing else; and
-- `booking_payments` was money against a booking with no receipt page, no channel and no list. This
-- migration completes the three rather than adding a second copy of each.
--
-- <h2>Two tables for where money lands, and the split is the design</h2>
--
-- A channel is a fact about a gateway ("KCB takes till credits"); an account is a fact about an
-- organisation ("ours is 7654321"). Collapsing them would have every developer re-describing M-Pesa, and
-- the catalogue row is what decides which fields an account must carry.
--
-- <h2>Void, not reversal</h2>
--
-- `booking_payments` corrected a payment with a second, negative row. A receipt is a record of what a
-- buyer was told, and a void with a reason beside it is a fresh fact rather than an edit — and a payments
-- list reads far better without negative receipts in it. Existing reversal pairs are folded: the original
-- becomes voided carrying the reversal's reason, by and when; the reversal row is archived. Status 4 is
-- this platform's INACTIVE, so every `status <> 5` guard in the codebase still means what it did.
--
-- <h2>The account identifier stays the inbound match key</h2>
--
-- The Pesi notification names the till it landed in, and that is resolved against `account_no` — which is
-- why `account_no` stays unique across live rows. `short_code` is kept as an optional secondary reference
-- the handler falls back to, not as the key.
-- ═════════════════════════════════════════════════════════════════════════════════════════════════

-- ── 1. The catalogue ─────────────────────────────────────────────────────────────────────────────

CREATE TABLE payment_types (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    /*
     * A stable name for the row. Configuration and screens refer to a channel by this, never by the
     * autoincrement id, so adding a channel renumbers nobody.
     */
    code                VARCHAR(40)  NOT NULL UNIQUE,
    name                VARCHAR(120) NOT NULL,
    description         VARCHAR(250),
    -- Who runs the rails: Safaricom, KCB, Co-operative Bank. Display only; there is no banks table here.
    provider_name       VARCHAR(120),

    -- Pesi's discriminator. Null for cash and cheque, the two channels with no gateway behind them.
    pesi_provider_type  VARCHAR(50),

    /*
     * CASH | CHEQUE | STK_PUSH | TRANSFER | VALIDATE — what the channel *is*, and therefore how it behaves.
     * Stored so a query can classify without re-deriving it from the provider string.
     */
    category            VARCHAR(16)  NOT NULL,

    /*
     * The coarse method a payment through this channel records. A column rather than a switch in Java:
     * choosing "Lipa na KCB" on the receive form must not be recordable as a cheque, and the channel is
     * the one place that knows what it amounts to.
     */
    method              VARCHAR(24)  NOT NULL,

    -- What the form must ask for. Stored rather than derived because the form is a different question.
    is_electronic       BOOLEAN      NOT NULL DEFAULT false,
    is_account_based    BOOLEAN      NOT NULL DEFAULT false,
    requires_short_code BOOLEAN      NOT NULL DEFAULT false,

    sort_order          INTEGER      NOT NULL DEFAULT 0,
    status              INTEGER      NOT NULL DEFAULT 1,
    status_flag         VARCHAR(32)  NOT NULL DEFAULT 'Active',
    search_text         TEXT GENERATED ALWAYS AS (
        lower(coalesce(name, '') || ' ' || coalesce(code, '') || ' ' || coalesce(provider_name, '')
              || ' ' || coalesce(description, ''))
    ) STORED,

    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by          VARCHAR(64),
    updated_by          VARCHAR(64),

    CONSTRAINT ck_payment_type_category CHECK (category IN
        ('CASH', 'CHEQUE', 'STK_PUSH', 'TRANSFER', 'VALIDATE')),
    CONSTRAINT ck_payment_type_method CHECK (method IN
        ('CASH', 'CHEQUE', 'BANK_TRANSFER', 'MOBILE_MONEY', 'CARD', 'OTHER')),
    -- A gateway channel without a provider cannot reach the gateway; a manual one must not claim to.
    CONSTRAINT ck_payment_type_provider CHECK (
        (category IN ('CASH', 'CHEQUE') AND pesi_provider_type IS NULL)
        OR (category NOT IN ('CASH', 'CHEQUE') AND pesi_provider_type IS NOT NULL)),
    -- Only an outbound channel can be started from the app.
    CONSTRAINT ck_payment_type_electronic CHECK (
        NOT is_electronic OR category IN ('STK_PUSH', 'TRANSFER'))
);

CREATE UNIQUE INDEX uk_payment_type_pesi ON payment_types (pesi_provider_type)
    WHERE pesi_provider_type IS NOT NULL;
CREATE INDEX idx_payment_types_order ON payment_types (sort_order) WHERE status <> 5;
CREATE INDEX idx_payment_types_search ON payment_types USING gin (search_text public.gin_trgm_ops);

