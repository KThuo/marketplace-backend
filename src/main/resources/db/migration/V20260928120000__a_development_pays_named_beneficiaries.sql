-- The people and companies a development pays, named once and paid many times.
--
-- Until now a cost carried a free-text payee: "Mwangi Hardware" on one line, "mwangi h/w" on the next, and
-- no way to say what kind of payee either was. A beneficiary is a record of its own, owned by the organisation
-- that pays it, reusable across that owner's developments, and confirmed with the bank before it can be paid.

-- ── what kind of payee ─────────────────────────────────────────────────────────────────────────────
--
-- A platform list, like cost categories: the bank adds a type without a deploy, and a suspended type keeps
-- its name on the beneficiaries already filed under it.
CREATE TABLE beneficiary_types (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(32)  NOT NULL UNIQUE,
    name        VARCHAR(120) NOT NULL,
    description TEXT,
    sort_order  INTEGER      NOT NULL DEFAULT 100,
    status      INTEGER      NOT NULL DEFAULT 1,
    status_flag VARCHAR(32)  NOT NULL DEFAULT 'Active',
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by  VARCHAR(64),
    updated_by  VARCHAR(64)
);

