-- ═════════════════════════════════════════════════════════════════════════════════════════════════
-- The assistant, phase 1 (claudedocs/ASSISTANT_PLAN.md)
--
-- Four things change shape here, each additive or a relaxed NOT NULL, so a running instance keeps
-- working through the deploy.
--
-- 1. A conversation may belong to a visitor. The browser keeps a random token; only its SHA-256 lands
--    here, so a copy of this table reads no conversation. Signing in moves the rows to the user and
--    clears the hash. `client_hash` is the hashed address, kept for the per-hour limit only.
-- 2. A conversation remembers. `context` holds the last search filters and the listings last shown, so
--    "what about under 15m?" refines rather than restarts, and "the second one" means something.
-- 3. An answer can be rated, and what it said is kept whole in `payload` (links and actions too), so a
--    conversation reopened tomorrow shows what was offered.
-- 4. What the assistant explains is a table the platform edits, not a map in code.
--
-- And one change outside the module: an enquiry may be about no listing at all, for a hand-off the
-- platform routes to its own staff or to a named organisation.
-- ═════════════════════════════════════════════════════════════════════════════════════════════════

ALTER TABLE assistant_conversations ALTER COLUMN user_id DROP NOT NULL;
ALTER TABLE assistant_conversations ADD COLUMN visitor_hash VARCHAR(64);
ALTER TABLE assistant_conversations ADD COLUMN client_hash  VARCHAR(64);
ALTER TABLE assistant_conversations ADD COLUMN context      JSONB;
ALTER TABLE assistant_conversations ADD CONSTRAINT ck_conversation_owner
    CHECK (user_id IS NOT NULL OR visitor_hash IS NOT NULL);

CREATE INDEX idx_conversation_visitor ON assistant_conversations (visitor_hash)
    WHERE visitor_hash IS NOT NULL;
CREATE INDEX idx_conversation_client ON assistant_conversations (client_hash, last_message_at)
    WHERE client_hash IS NOT NULL;

ALTER TABLE assistant_messages ADD COLUMN rating   SMALLINT;
ALTER TABLE assistant_messages ADD COLUMN rated_at TIMESTAMPTZ;
ALTER TABLE assistant_messages ADD CONSTRAINT ck_message_rating CHECK (rating IS NULL OR rating IN (-1, 1));

-- What the insights page reads: answers by intent over a period, and the ones somebody disliked.
CREATE INDEX idx_message_intent ON assistant_messages (created_at DESC, intent) WHERE side = 'ASSISTANT';
CREATE INDEX idx_message_disliked ON assistant_messages (created_at DESC) WHERE rating = -1;


-- ── what it explains ─────────────────────────────────────────────────────────────────────────────
CREATE TABLE assistant_knowledge (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference   VARCHAR(16)  NOT NULL UNIQUE,

    -- The word somebody asks about, and the other ways they say it, one per line.
    term        VARCHAR(80)  NOT NULL,
    phrasings   TEXT,
    answer      TEXT         NOT NULL,

    -- Somewhere worth going next, optional. A path inside this application.
    link_label  VARCHAR(80),
    link_to     VARCHAR(255),

    active      BOOLEAN      NOT NULL DEFAULT TRUE,

    status      INTEGER      NOT NULL DEFAULT 1,
    status_flag VARCHAR(32)  NOT NULL DEFAULT 'Active',
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by  VARCHAR(64),
    updated_by  VARCHAR(64),

    CONSTRAINT ck_knowledge_link CHECK ((link_label IS NULL) = (link_to IS NULL))
);

CREATE UNIQUE INDEX uk_knowledge_term ON assistant_knowledge (lower(term)) WHERE status <> 5;

