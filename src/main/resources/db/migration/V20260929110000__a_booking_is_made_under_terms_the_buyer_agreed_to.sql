-- ── what each booking was agreed under ────────────────────────────────────────────────────────────────
CREATE TABLE booking_terms (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id        BIGINT       NOT NULL REFERENCES unit_bookings (id),
    template_version  INTEGER      NOT NULL REFERENCES booking_terms_templates (version),
    -- The figures the template was filled with that day: price, deposit, plan, hold, penalty, windows, note.
    figures           JSONB        NOT NULL,
    presented_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    accepted_at       TIMESTAMPTZ,
    declined_at       TIMESTAMPTZ,
    decline_reason    TEXT,
    -- PORTAL: the buyer, signed in. PAPER: the sales office, with the signed form in the vault.
    channel           VARCHAR(8),
    decided_by_user_id BIGINT,
    decided_by_name   VARCHAR(160),
    -- The signed form, when accepted on paper.
    document_id       BIGINT REFERENCES vault_documents (id),
    -- A buyer confirming in the portal what they had signed on paper.
    confirmed_at      TIMESTAMPTZ,
    superseded_at     TIMESTAMPTZ,
    created_by        VARCHAR(64)
);
CREATE INDEX idx_booking_terms_booking ON booking_terms (booking_id, presented_at DESC);

-- NONE: made before terms existed, or a completed sale recorded by hand. PRESENTED: waiting for the
-- buyer. ACCEPTED, DECLINED: their answer.
ALTER TABLE unit_bookings
    ADD COLUMN terms_state             VARCHAR(10) NOT NULL DEFAULT 'NONE',
    ADD COLUMN expiry_reminder_sent_at TIMESTAMPTZ;

ALTER TABLE unit_bookings
    ADD CONSTRAINT ck_booking_terms_state CHECK (terms_state IN ('NONE', 'PRESENTED', 'ACCEPTED', 'DECLINED'));
