-- A booking is made under terms the buyer agreed to.
--
-- Everything that can cost the buyer money — the hold and when it lapses, the deposit, the plan, what a
-- refund keeps back, that a cancellation is final — is told to them before they commit, and their answer
-- is kept. The terms are one page: a versioned template at the platform, filled with the live figures of
-- any booking or listing. What acceptance keeps is the version and the figures, so a later change to the
-- rate or the wording does not rewrite what was agreed.

-- ── the policy, per development; null means the platform default ──────────────────────────────────────
ALTER TABLE developments
    ADD COLUMN refund_penalty_basis              VARCHAR(20),
    ADD COLUMN refund_penalty_rate               NUMERIC(15, 3),
    ADD COLUMN refund_penalty_cap                NUMERIC(15, 2),
    ADD COLUMN refund_penalty_bank_share_percent NUMERIC(6, 3),
    ADD COLUMN refund_within_days                INTEGER,
    ADD COLUMN revive_within_days                INTEGER,
    ADD COLUMN booking_policy_note               TEXT;

ALTER TABLE developments
    ADD CONSTRAINT ck_dev_refund_penalty_basis CHECK (refund_penalty_basis IS NULL
        OR refund_penalty_basis IN ('PERCENT_OF_PAID', 'PERCENT_OF_DEPOSIT', 'FIXED'));

-- ── the template: one page, versioned ─────────────────────────────────────────────────────────────────
CREATE TABLE booking_terms_templates (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version     INTEGER      NOT NULL UNIQUE,
    body        TEXT         NOT NULL,
    note        VARCHAR(255),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by  VARCHAR(64)
);

