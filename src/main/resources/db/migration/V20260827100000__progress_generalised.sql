-- ── the widened table ────────────────────────────────────────────────────────────────────────────

ALTER TABLE listing_progress_updates
    ALTER COLUMN property_id DROP NOT NULL,
    ALTER COLUMN tenant_id   DROP NOT NULL,
    ADD COLUMN development_id BIGINT      REFERENCES developments (id),
    ADD COLUMN phase_id       BIGINT      REFERENCES development_phases (id),
    ADD COLUMN unit_id        BIGINT      REFERENCES development_units (id),
    ADD COLUMN institution_id BIGINT,
    ADD COLUMN milestone_code VARCHAR(32) REFERENCES progress_milestone_configs (code),
    ADD COLUMN image_count    INTEGER     NOT NULL DEFAULT 0;

-- One subject, never two and never none. Validates immediately: every existing row has property_id.
ALTER TABLE listing_progress_updates ADD CONSTRAINT ck_progress_subject CHECK (
    (property_id IS NOT NULL)::int + (development_id IS NOT NULL)::int = 1);

-- A phase or a unit only makes sense under a development. Without this, an update against a listing could
-- carry another project's phase and no query would notice.
ALTER TABLE listing_progress_updates ADD CONSTRAINT ck_progress_child_needs_development CHECK (
    development_id IS NOT NULL OR (phase_id IS NULL AND unit_id IS NULL));

-- Who may see it, cached from the subject so an access check is one read rather than a walk up the tree.
-- Not "exactly one": a listing update has a tenant, a bank's project has an institution, and a
-- platform-owned project has neither.
ALTER TABLE listing_progress_updates ADD CONSTRAINT ck_progress_owner CHECK (
    (institution_id IS NULL) OR (tenant_id IS NULL));

ALTER TABLE listing_progress_updates ADD CONSTRAINT ck_progress_image_count CHECK (image_count >= 0);

COMMENT ON COLUMN listing_progress_updates.milestone IS
    'The free text the reporter typed. milestone_code is the stable identifier; this stays because eight '
    'names chosen by us are not the eight every developer uses.';
COMMENT ON COLUMN listing_progress_updates.image_key IS
    'Cover photograph. A cache over media_assets for PROGRESS_UPDATE, so rows written before that table '
    'existed still render.';

-- ── indexes for the two new reads ────────────────────────────────────────────────────────────────

CREATE INDEX idx_progress_development ON listing_progress_updates (development_id, reported_on DESC)
    WHERE development_id IS NOT NULL AND status <> 5;

-- The development's public timeline: published rows for one project.
CREATE INDEX idx_progress_development_public ON listing_progress_updates (development_id, reported_on DESC)
    WHERE development_id IS NOT NULL AND published AND status <> 5;

-- The cross-project feed on the public site. No leading subject column, because this query has no subject:
-- it is "everything published, newest first", paged. Ordered by id as well so a page boundary between two
-- updates reported on the same day is stable — without it the second page can repeat or skip a row.
CREATE INDEX idx_progress_feed ON listing_progress_updates (reported_on DESC, id DESC)
    WHERE published AND status <> 5;
