-- ─────────────────────────────────────────────────────────────────────────────────────────────────
-- The vendor.
--
-- Same shape as an agent, and deliberately so: apply, be approved, get an organisation. The differences are
-- what is checked (a business registration rather than an estate agent's licence) and what they publish.
-- ─────────────────────────────────────────────────────────────────────────────────────────────────
CREATE TABLE vendor_profiles (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    reference          VARCHAR(16)  NOT NULL UNIQUE,
    user_id            BIGINT       NOT NULL REFERENCES users (id),
    profile_id         BIGINT       NOT NULL REFERENCES user_profiles (id),
    -- Set at approval, exactly like an agent's. No organisation means nowhere to publish a catalogue.
    tenant_id          BIGINT       REFERENCES tenants (id),

    business_name      VARCHAR(255) NOT NULL,
    contact_name       VARCHAR(160),
    email              VARCHAR(128),
    phone              VARCHAR(32),

    category_id        BIGINT       NOT NULL REFERENCES vendor_categories (id),
    category_name      VARCHAR(120),

    registration_number VARCHAR(64),
    kra_pin            VARCHAR(32),
    counties           TEXT,
    about              TEXT,
    website            VARCHAR(255),
    logo_key           VARCHAR(512),

    state              VARCHAR(16)  NOT NULL DEFAULT 'PENDING',
    decided_at         TIMESTAMPTZ,
    decided_by_user_id BIGINT,
    decision_note      TEXT,

    status             INTEGER      NOT NULL DEFAULT 1,
    status_flag        VARCHAR(32)  NOT NULL DEFAULT 'Active',

    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by         VARCHAR(64),
    updated_by         VARCHAR(64),

    CONSTRAINT uk_vendor_profile UNIQUE (profile_id),
    CONSTRAINT ck_vendor_state CHECK (state IN ('PENDING', 'APPROVED', 'REJECTED', 'SUSPENDED')),
    CONSTRAINT ck_vendor_approved CHECK (
        state <> 'APPROVED' OR (tenant_id IS NOT NULL AND decided_at IS NOT NULL)),
    CONSTRAINT ck_vendor_decided CHECK (state <> 'REJECTED' OR decided_at IS NOT NULL)
