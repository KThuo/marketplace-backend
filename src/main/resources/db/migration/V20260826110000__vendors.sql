-- ─────────────────────────────────────────────────────────────────────────────────────────────────
-- One thing a vendor offers.
--
-- Prices are honest about their own precision. A conveyancer quotes a percentage of the purchase price, a
-- mover quotes per trip, a surveyor quotes a flat fee — so `price` is optional, `price_from` says "from",
-- and `price_note` carries the sentence a number cannot ("1.5% of the purchase price, minimum KES 35,000").
-- Forcing all of that into one number is how a marketplace ends up displaying prices nobody will honour.
-- ─────────────────────────────────────────────────────────────────────────────────────────────────
CREATE TABLE catalogue_items (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    reference       VARCHAR(16)  NOT NULL UNIQUE,
    vendor_id       BIGINT       NOT NULL REFERENCES vendor_profiles (id),
    tenant_id       BIGINT,
    vendor_name     VARCHAR(255),

    category_id     BIGINT       NOT NULL REFERENCES vendor_categories (id),
    category_name   VARCHAR(120),

    title           VARCHAR(255) NOT NULL,
    description     TEXT,

    price           NUMERIC(15, 2),
    price_from      BOOLEAN      NOT NULL DEFAULT false,
    currency        VARCHAR(3)   NOT NULL DEFAULT 'KES',
    unit            VARCHAR(32),
    price_note      TEXT,

    lead_time_days  SMALLINT,
    counties        TEXT,
    image_key       VARCHAR(512),

    state           VARCHAR(16)  NOT NULL DEFAULT 'DRAFT',
    published_at    TIMESTAMPTZ,
    withdrawn_at    TIMESTAMPTZ,
    withdrawn_reason TEXT,

    status          INTEGER      NOT NULL DEFAULT 1,
    status_flag     VARCHAR(32)  NOT NULL DEFAULT 'Active',

    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by      VARCHAR(64),
    updated_by      VARCHAR(64),

    CONSTRAINT ck_item_state CHECK (state IN ('DRAFT', 'PENDING', 'LIVE', 'WITHDRAWN')),
    CONSTRAINT ck_item_published CHECK (state <> 'LIVE' OR published_at IS NOT NULL),
    -- A published item says something about price. Not necessarily a number — but not silence either.
    CONSTRAINT ck_item_priced CHECK (
        state <> 'LIVE' OR price IS NOT NULL OR (price_note IS NOT NULL AND price_note <> ''))
);

CREATE INDEX idx_item_vendor ON catalogue_items (vendor_id, created_at DESC);
CREATE INDEX idx_item_category ON catalogue_items (category_id);
-- The public catalogue: live, newest first. Its own partial index, like the auction one.
CREATE INDEX idx_item_public ON catalogue_items (published_at DESC)
    WHERE state = 'LIVE' AND status <> 5;

ALTER TABLE catalogue_items ADD COLUMN search_text text
    GENERATED ALWAYS AS (
        lower(coalesce(reference, '') || ' ' || coalesce(title, '') || ' ' ||
              coalesce(description, '') || ' ' || coalesce(vendor_name, '') || ' ' ||
              coalesce(category_name, '') || ' ' || coalesce(counties, '') || ' ' ||
              coalesce(price_note, ''))
    ) STORED;
CREATE INDEX idx_item_search_trgm ON catalogue_items USING gin (search_text gin_trgm_ops);

-- ─────────────────────────────────────────────────────────────────────────────────────────────────
-- The modules an approved vendor works in. Appended, token-precise, and only where the row is untouched —
-- see the M9 migration for why `allowed_user_types` is not simply re-seeded.
-- ─────────────────────────────────────────────────────────────────────────────────────────────────
UPDATE app_modules
SET allowed_user_types = allowed_user_types || ',VENDOR',
    updated_at         = now(),
    updated_by         = 'system'
WHERE code IN ('DASHBOARD', 'APPROVALS')
  AND ',' || allowed_user_types || ',' NOT LIKE '%,VENDOR,%';
