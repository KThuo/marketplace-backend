-- Phase 4 / M10 — the vendor marketplace (BRD FR170, plan §3.6)
--
-- The other half of buying a house. Somebody who has just had an offer accepted needs a conveyancer, a
-- surveyor, a mover, a bank valuer's fee paid, curtains and a security firm — and the platform already knows
-- exactly when they need them. A vendor is a business offering those services, and a catalogue item is one
-- thing they offer.
--
-- <h2>A vendor is an organisation, like an agent</h2>
--
-- §3.6 said vendors are "organisation-scoped exactly like sellers, so they reuse TenantScope unchanged", and
-- that is what happens: an approved vendor gets a `tenants` row of kind VENDOR, and everything downstream —
-- visibility, module enablement, staff — works without a new mechanism. The kind column added for agents is
-- what keeps them out of the seller administration screen.
--
-- <h2>The catalogue goes through Maker/Checker</h2>
--
-- Plan §3.2 lists M10 as a consumer of the approval queue, and it is the right call for a reason worth
-- writing down: a catalogue item is a public price from a third party, shown to somebody in the middle of
-- the largest transaction of their life. A seller's listing is checked before it is published; a vendor's
-- quotation should be too.
--
-- <h2>What is NOT here</h2>
--
-- `product_rating` from the §4 table. Ratings arrive in M7 as one mechanism covering property, service and
-- product, rather than a product-only table now and a general one a fortnight later that has to absorb it.
-- ═════════════════════════════════════════════════════════════════════════════════════════════════

