-- Phase 5 / M13 — internal management, seller side (plan §4)
--
-- Three tables the §4 plan names: `property_type_config`, `promotion_package`, `commission_record`. All
-- three exist because something is currently hardcoded, unpriced or uncounted.
--
-- <h2>1. The property types stop being a hardcoded list</h2>
--
-- Six values live in a Java enum, three Vue arrays and a form's validation. Adding "godown" or "serviced
-- apartment" today means a deploy in two repositories, and the fields the form asks for are decided by a
-- switch nobody can see. A table lets the platform add a type, say which of bedrooms, floor area and plot
-- area apply to it, and have every form follow.
--
-- <h2>2. Promotion, without inventing a payment flow</h2>
--
-- A package is what the platform sells: a placement for a number of days at a price. A promotion is one
-- listing holding one package for a window. The platform does not take the money here — there is no payments
-- integration and pretending otherwise would be the worst kind of half-feature — so a seller *requests* a
-- promotion and the platform activates it once they have been paid however they were paid.
--
-- <h2>3. Commission, raised when a sale completes</h2>
--
-- The platform earns on a completed sale, and until now nothing recorded that. A commission is raised from
-- the rate in force at the moment a listing is marked sold, and the rate is **copied onto the row** rather
-- than referenced: a rate change next quarter must not silently restate what was owed last quarter.
-- ═════════════════════════════════════════════════════════════════════════════════════════════════

CREATE TABLE property_type_configs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code            VARCHAR(32)  NOT NULL UNIQUE,
    name            VARCHAR(120) NOT NULL,
    description     TEXT,
    icon            VARCHAR(8),
    sort_order      INTEGER      NOT NULL DEFAULT 100,

    -- Which questions a listing of this kind should be asked. A godown has a floor area and no bedrooms;
    -- land has a plot area and neither. Today that is a switch nobody can see.
    has_bedrooms    BOOLEAN      NOT NULL DEFAULT true,
    has_bathrooms   BOOLEAN      NOT NULL DEFAULT true,
    has_floor_area  BOOLEAN      NOT NULL DEFAULT true,
    has_plot_area   BOOLEAN      NOT NULL DEFAULT false,
    has_year_built  BOOLEAN      NOT NULL DEFAULT true,
    -- Whether a listing of this kind may be let rather than sold.
    lettable        BOOLEAN      NOT NULL DEFAULT true,

    status          INTEGER      NOT NULL DEFAULT 1,
    status_flag     VARCHAR(32)  NOT NULL DEFAULT 'Active',

    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by      VARCHAR(64),
    updated_by      VARCHAR(64)
);

