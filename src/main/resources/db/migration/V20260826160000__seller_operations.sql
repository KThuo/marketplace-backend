-- ─────────────────────────────────────────────────────────────────────────────────────────────────
-- One listing holding one package for a window.
--
-- The price and the placement are copied onto the row. A package repriced next month must not restate what
-- somebody bought last month — the same reasoning as the commission rate below.
-- ─────────────────────────────────────────────────────────────────────────────────────────────────
CREATE TABLE listing_promotions (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    reference         VARCHAR(16)  NOT NULL UNIQUE,
    property_id       BIGINT       NOT NULL REFERENCES properties (id),
    property_ref      VARCHAR(16),
    property_title    VARCHAR(255),
    tenant_id         BIGINT       NOT NULL,
    tenant_name       VARCHAR(255),

    package_id        BIGINT       NOT NULL REFERENCES promotion_packages (id),
    package_name      VARCHAR(120),
    placement         VARCHAR(24)  NOT NULL,
    boost             INTEGER      NOT NULL DEFAULT 10,
    price             NUMERIC(15, 2) NOT NULL,
    currency          VARCHAR(3)   NOT NULL DEFAULT 'KES',
    duration_days     INTEGER      NOT NULL,

    -- REQUESTED | ACTIVE | EXPIRED | CANCELLED. The platform activates once it has been paid, however it
    -- was paid — there is no payments integration here and pretending otherwise would be worse than saying
    -- so.
    state             VARCHAR(16)  NOT NULL DEFAULT 'REQUESTED',
    starts_at         TIMESTAMPTZ,
    ends_at           TIMESTAMPTZ,
    activated_by_user_id BIGINT,
    cancelled_reason  TEXT,
    note              TEXT,

    status            INTEGER      NOT NULL DEFAULT 1,
    status_flag       VARCHAR(32)  NOT NULL DEFAULT 'Active',

    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by        VARCHAR(64),
    updated_by        VARCHAR(64),

    CONSTRAINT ck_promotion_state
        CHECK (state IN ('REQUESTED', 'ACTIVE', 'EXPIRED', 'CANCELLED')),
    CONSTRAINT ck_promotion_window CHECK (
        state <> 'ACTIVE' OR (starts_at IS NOT NULL AND ends_at IS NOT NULL AND ends_at > starts_at))
);

-- One live promotion per listing. Two at once is two people's money buying the same placement.
CREATE UNIQUE INDEX uk_promotion_live ON listing_promotions (property_id)
    WHERE state IN ('REQUESTED', 'ACTIVE') AND status <> 5;
CREATE INDEX idx_promotion_active ON listing_promotions (ends_at)
    WHERE state = 'ACTIVE' AND status <> 5;
CREATE INDEX idx_promotion_tenant ON listing_promotions (tenant_id, created_at DESC);

ALTER TABLE listing_promotions ADD COLUMN search_text text
    GENERATED ALWAYS AS (
        lower(coalesce(reference, '') || ' ' || coalesce(property_ref, '') || ' ' ||
              coalesce(property_title, '') || ' ' || coalesce(tenant_name, '') || ' ' ||
              coalesce(package_name, '') || ' ' || coalesce(state, ''))
    ) STORED;
CREATE INDEX idx_promotion_search_trgm ON listing_promotions USING gin (search_text public.gin_trgm_ops);

-- The boost a listing currently carries, denormalised so marketplace search sorts without a join. Written
-- by PromotionService and by nothing else.
ALTER TABLE properties ADD COLUMN promotion_boost INTEGER NOT NULL DEFAULT 0;
ALTER TABLE properties ADD COLUMN promoted_until TIMESTAMPTZ;
CREATE INDEX idx_property_boost ON properties (promotion_boost DESC)
    WHERE listing_state = 'LIVE' AND status <> 5;

-- ─────────────────────────────────────────────────────────────────────────────────────────────────
-- What the platform earned.
--
-- Raised when a listing is marked sold, from the rate in force at that moment. The rate is copied onto the
-- row: a rate change next quarter must not silently restate what was owed last quarter.
-- ─────────────────────────────────────────────────────────────────────────────────────────────────
CREATE TABLE commission_records (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    reference       VARCHAR(16)  NOT NULL UNIQUE,

    property_id     BIGINT       NOT NULL REFERENCES properties (id),
    property_ref    VARCHAR(16),
    property_title  VARCHAR(255),
    tenant_id       BIGINT       NOT NULL,
    tenant_name     VARCHAR(255),

    sale_price      NUMERIC(15, 2) NOT NULL,
    -- The rate as it stood, not a pointer to a setting that will change.
    rate_percent    NUMERIC(6, 3)  NOT NULL,
    amount          NUMERIC(15, 2) NOT NULL,
    currency        VARCHAR(3)   NOT NULL DEFAULT 'KES',

    sold_at         TIMESTAMPTZ  NOT NULL,

    -- DUE | INVOICED | PAID | WAIVED
    state           VARCHAR(16)  NOT NULL DEFAULT 'DUE',
    invoice_ref     VARCHAR(64),
    invoiced_at     TIMESTAMPTZ,
    paid_at         TIMESTAMPTZ,
    waived_reason   TEXT,
    note            TEXT,

    status          INTEGER      NOT NULL DEFAULT 1,
    status_flag     VARCHAR(32)  NOT NULL DEFAULT 'Active',

    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by      VARCHAR(64),
    updated_by      VARCHAR(64),

    CONSTRAINT ck_commission_state CHECK (state IN ('DUE', 'INVOICED', 'PAID', 'WAIVED')),
    CONSTRAINT ck_commission_paid CHECK (state <> 'PAID' OR paid_at IS NOT NULL),
    -- Waiving money says why. A waiver with no reason is not a decision anybody can review afterwards.
    CONSTRAINT ck_commission_waived CHECK (state <> 'WAIVED' OR waived_reason IS NOT NULL)
);

-- One commission per sale. A listing sold twice is a listing relisted, and that is a second row on a
-- second sale — but not two rows for one.
CREATE UNIQUE INDEX uk_commission_per_sale ON commission_records (property_id, sold_at);
CREATE INDEX idx_commission_state ON commission_records (state, sold_at DESC);
CREATE INDEX idx_commission_tenant ON commission_records (tenant_id, sold_at DESC);

ALTER TABLE commission_records ADD COLUMN search_text text
    GENERATED ALWAYS AS (
        lower(coalesce(reference, '') || ' ' || coalesce(property_ref, '') || ' ' ||
              coalesce(property_title, '') || ' ' || coalesce(tenant_name, '') || ' ' ||
              coalesce(invoice_ref, '') || ' ' || coalesce(state, ''))
    ) STORED;
CREATE INDEX idx_commission_search_trgm ON commission_records USING gin (search_text public.gin_trgm_ops);
