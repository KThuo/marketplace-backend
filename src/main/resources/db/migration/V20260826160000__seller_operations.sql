-- ─────────────────────────────────────────────────────────────────────────────────────────────────
-- What the platform sells.
-- ─────────────────────────────────────────────────────────────────────────────────────────────────
CREATE TABLE promotion_packages (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    reference       VARCHAR(16)  NOT NULL UNIQUE,
    code            VARCHAR(32)  NOT NULL UNIQUE,
    name            VARCHAR(120) NOT NULL,
    description     TEXT,

    -- FEATURED | TOP_OF_SEARCH | HOMEPAGE. What the placement actually does, so search can act on it
    -- rather than on the package's name.
    placement       VARCHAR(24)  NOT NULL,
    duration_days   INTEGER      NOT NULL,
    price           NUMERIC(15, 2) NOT NULL,
    currency        VARCHAR(3)   NOT NULL DEFAULT 'KES',

    -- How hard it lifts a listing in search results. A number rather than an order, so two packages can
    -- coexist without one implying the other's rank.
    boost           INTEGER      NOT NULL DEFAULT 10,

    status          INTEGER      NOT NULL DEFAULT 1,
    status_flag     VARCHAR(32)  NOT NULL DEFAULT 'Active',

    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by      VARCHAR(64),
    updated_by      VARCHAR(64),

    CONSTRAINT ck_package_placement
        CHECK (placement IN ('FEATURED', 'TOP_OF_SEARCH', 'HOMEPAGE')),
    CONSTRAINT ck_package_duration CHECK (duration_days > 0),
    CONSTRAINT ck_package_price CHECK (price >= 0)
);

