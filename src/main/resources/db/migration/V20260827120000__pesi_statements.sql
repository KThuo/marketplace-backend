-- Where every payment Pesi tells us about lands
--
-- The reconciliation surface, kept separate from `booking_payments` on purpose. A statement is "Pesi says
-- money arrived"; a payment is "this booking has been paid". Most of the time those are the same event, and
-- the whole value of this table is the times they are not: a mistyped reference, a walk-in payer, a deposit
-- against a unit that was cancelled last week.
--
-- <h2>Store first, match second, and never make Pesi retry</h2>
--
-- The guide is explicit: no match → insert UNMAPPED anyway and still return success. A retry does not help,
-- because the reference will be just as wrong next time, and each retry is another chance to double-post. So
-- the only thing that must succeed in the handler is writing the row. Matching is best-effort on top of it.
--
-- <h2>Two tiers of catalogue, plus an owner the guide does not mention</h2>
--
-- `pesi_super_types` is "what does this Pesi code mean"; `pesi_payment_methods` is "which of our accounts does
-- it settle to". That separation is the guide's §4.1, and it means a new till is a config row rather than a
-- deploy.
--
-- The column the guide has no reason to mention is the **owner** on each method. This platform is one Pesi
-- business with many tills, each assigned to whoever collects on it — the bank for its own developments, a
-- developer for theirs. An inbound notification carries `accountIdentifier`, which resolves the till, which
-- resolves whose money it is. Nobody needs their own API key and the platform never holds the money.
-- ═════════════════════════════════════════════════════════════════════════════════════════════════

CREATE TABLE pesi_super_types (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- The Pesi code, e.g. BUNI_IPN_TILL. Theirs, not ours; not translated.
    code                    VARCHAR(48)  NOT NULL UNIQUE,
    name                    VARCHAR(120) NOT NULL,
    /*
     * STK_PUSH | IPN | FT | QUERY | BILLER.
     *
     * Which of the guide's rows applies, and therefore what a form should ask for. Only IPN is used today —
     * the rest are here because the catalogue is worthless if it only holds the codes already in use.
     */
    category                VARCHAR(24)  NOT NULL,

    requires_phone          BOOLEAN      NOT NULL DEFAULT false,
    requires_account_number BOOLEAN      NOT NULL DEFAULT false,

    status                  INTEGER      NOT NULL DEFAULT 1,
    status_flag             VARCHAR(32)  NOT NULL DEFAULT 'Active',
    created_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by              VARCHAR(64),
    updated_by              VARCHAR(64),

    CONSTRAINT ck_pesi_category CHECK (category IN ('STK_PUSH', 'IPN', 'FT', 'QUERY', 'BILLER'))
);

-- The five inbound codes from the guide's §3. One handler serves all of them; this is what lets a payload
-- naming one of them be recognised without an if/else over magic strings.
